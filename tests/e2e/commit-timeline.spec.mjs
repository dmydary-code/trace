import {test, expect, addComment} from './fixtures.mjs';
import {eventually} from '../support/harness.mjs';
import {writeFile} from 'node:fs/promises';
import {join} from 'node:path';

async function expectTimelineOnRight(page) {
  const detail = await page.locator('main').boundingBox();
  const rail = await page.locator('#timeline').boundingBox();
  expect(rail.x).toBeCloseTo(detail.x + detail.width, 0);
  expect(rail.y).toBeCloseTo((await page.locator('header').boundingBox()).height, 0);
  expect(rail.x + rail.width).toBeLessThanOrEqual(page.viewportSize().width + 1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize().width);
}

test('approve one commit, discuss another twice, return to Overall', async ({page, f}) => {
  await f.git('checkout', '-b', 'shipping');
  await f.git('commit', '-am', 'Include shipping');
  await f.put('currency.txt', 'EUR\n');
  await f.git('add', 'currency.txt');
  await f.git('commit', '-m', 'Set currency', '-m', 'Use the billing currency.');
  const sha = await f.git('rev-parse', 'HEAD');
  await f.put('currency.txt', 'USD\n');
  const run = await f.start({args:['--listen', '--base', 'main']});
  const feedback = () => run.events.filter(e => e.event === 'feedback');
  await page.goto(run.ready.url);
  await page.locator('#timeline-open').click();
  const rows = page.locator('#commit-list a');
  await expect(rows).toHaveCount(2);
  await expect(page.locator('#title')).toHaveText('Include shipping');
  await expectTimelineOnRight(page);
  const files = await page.locator('#file-sidebar').boundingBox();
  expect(files.x + files.width).toBeCloseTo((await page.locator('main').boundingBox()).x, 0);
  await page.getByRole('button', {name:'Toggle file sidebar'}).click();
  await expect(page.locator('#file-sidebar')).toBeHidden();
  await expectTimelineOnRight(page);
  await page.locator('#commit-approve').click();
  await expect(page.locator('#commit-approve')).toBeDisabled();
  await expect(rows.first()).toHaveAttribute('aria-current', 'page');
  await expect(rows.first().locator('.commit-mark')).toBeVisible();
  await expect(rows.last().locator('.commit-mark')).toBeHidden();
  await rows.last().click();
  await expect(rows.first()).toBeInViewport();
  await expect(rows.last()).toHaveAttribute('aria-current', 'page');
  await expect(rows.last().locator('code')).toHaveText(sha.slice(0, 8));
  await expect(page.locator('#commit-body')).toHaveText('Use the billing currency.');
  await expect(page.locator('#feed')).toContainText('EUR');
  await expect(page.locator('#feed')).not.toContainText('USD');
  await addComment(page, 'Why EUR?');
  await page.locator('#review').click();
  await page.locator('#send').click();
  const first = await eventually(() => feedback()[0]);
  expect(first.commit.sha).toBe(sha);
  expect(first.comments[0]).toMatchObject({path:'currency.txt',line:1,side:'new',code:'EUR'});
  const body = join(f.dir, 'reply.txt');
  await writeFile(body, 'It matches the billing account.');
  await f.cli('reply', '--review', first.id, '--comment', first.comments[0].id, '--body-file', body, '--agent', 'codex', '--status', 'note');
  await expect(page.locator('.agent-reply')).toContainText('billing account');
  await page.locator('[data-followup]').click();
  await page.getByRole('textbox', {name:'Reply',exact:true}).fill('Where is the account configured?');
  await page.getByRole('button', {name:'Send reply'}).click();
  const next = await eventually(() => feedback()[1]);
  expect(next.sessionId).toBe(first.sessionId);
  expect(next.commit.sha).toBe(sha);
  expect(next.replyTo).toEqual({reviewId:first.id,commentId:first.comments[0].id});
  await expect(page.locator('.thread-history')).toContainText('billing account');
  await page.locator('#overall-scope').click();
  await expect(page.locator('#title')).toHaveText('Overall changes');
  await expect(page.locator('#timeline')).toBeHidden();
  await expect(page.locator('#feed')).toContainText('USD');
  await expect(page.locator('#feed')).toContainText(f.project.path);
  await expect(page.locator('#commit-approve')).toBeHidden();
  await page.locator('#timeline-open').click();
  await expect(rows.first()).toContainText('Approved');
  await rows.last().click();
  await expect(page.locator('.file-card .thread')).toContainText('Where is the account configured?');
  await run.end();
  expect(await run.exited).toBe(0);
});

test('a deep-linked timeline keeps its place when reading adjacent commits on a narrow screen', async ({page, f}) => {
  await f.git('checkout', '-b', 'steps');
  for (let step = 1; step <= 16; step++) {
    await f.put('steps.txt', String(step) + '\n');
    await f.git('add', 'steps.txt');
    await f.git('commit', '-m', 'Step ' + step);
  }
  const app = await f.server({base:'main'});
  const tip = await f.git('rev-parse', 'HEAD');
  await page.setViewportSize({width:390, height:844});
  await page.goto(app.url + '/?scope=' + tip);
  const list = page.locator('#commit-list');
  const link = step => list.getByRole('link', {name:new RegExp('^Step ' + step + ' ')});
  await expect(link(16)).toBeInViewport();
  await expect(link(16)).toHaveAttribute('aria-current', 'page');
  await expectTimelineOnRight(page);
  const offset = await list.evaluate(el => el.scrollTop);
  expect(offset).toBeGreaterThan(0);
  await link(15).click();
  await expect(page.locator('#title')).toHaveText('Step 15');
  await expect(link(15)).toHaveAttribute('aria-current', 'page');
  expect(await list.evaluate(el => el.scrollTop)).toBeCloseTo(offset, 0);
  await page.goBack();
  await expect(link(16)).toHaveAttribute('aria-current', 'page');
  await page.reload();
  await expect(link(16)).toBeInViewport();
  await expect(page.locator('#title')).toHaveText('Step 16');
  await page.setViewportSize({width:581, height:780});
  await expectTimelineOnRight(page);
  const toggle = page.getByRole('button', {name:'Toggle file sidebar'});
  await toggle.click();
  await expect(page.getByRole('searchbox')).toBeFocused();
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await expect(link(16)).toBeInViewport();
  await page.keyboard.press('Escape');
  await expect(page.locator('#file-sidebar')).toBeHidden();
  await expect(toggle).toBeFocused();
  await link(15).click();
  await expect(page.locator('#title')).toHaveText('Step 15');
  await expect(link(16)).toBeInViewport();
});
