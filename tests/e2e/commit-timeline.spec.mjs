import {test, expect, addComment} from './fixtures.mjs';
import {eventually} from '../support/harness.mjs';
import {writeFile} from 'node:fs/promises';
import {join} from 'node:path';

test('approve one commit, discuss another twice, return to Overall', async ({page, f}) => {
  await f.git('checkout', '-b', 'shipping');
  await f.git('commit', '-am', 'Include shipping');
  await f.put('currency.txt', 'EUR\n');
  await f.git('add', 'currency.txt');
  await f.git('commit', '-m', 'Set currency', '-m', 'Use the billing currency.');
  const sha = await f.git('rev-parse', 'HEAD');
  await f.put('currency.txt', 'USD\n');
  const run = await f.start({args:['--listen', '--base', 'main']});
  const feedback = () => run.events.filter(e => e.event === 'feedback');
  await page.goto(run.ready.url);
  await page.locator('#timeline-open').click();
  const rows = page.locator('#commit-list button');
  await expect(rows).toHaveCount(2);
  await rows.first().click();
  await expect(page.locator('#title')).toHaveText('Include shipping');
  await page.locator('#commit-approve').click();
  await expect(page.locator('#commit-approve')).toBeDisabled();
  await page.locator('#timeline-open').click();
  await expect(rows.first()).toContainText('Approved');
  await expect(rows.last()).not.toContainText('Approved');
  await rows.last().click();
  await expect(page.locator('#commit-body')).toHaveText('Use the billing currency.');
  await expect(page.locator('#feed')).toContainText('EUR');
  await expect(page.locator('#feed')).not.toContainText('USD');
  await addComment(page, 'Why EUR?');
  await page.locator('#review').click();
  await page.locator('#send').click();
  const first = await eventually(() => feedback()[0]);
  expect(first.commit.sha).toBe(sha);
  expect(first.comments[0]).toMatchObject({path:'currency.txt',line:1,side:'new',code:'EUR'});
  const body = join(f.dir, 'reply.txt');
  await writeFile(body, 'It matches the billing account.');
  await f.cli('reply', '--review', first.id, '--comment', first.comments[0].id, '--body-file', body, '--agent', 'codex', '--status', 'note');
  await expect(page.locator('.agent-reply')).toContainText('billing account');
  await page.locator('[data-followup]').click();
  await page.getByRole('textbox', {name:'Reply',exact:true}).fill('Where is the account configured?');
  await page.getByRole('button', {name:'Send reply'}).click();
  const next = await eventually(() => feedback()[1]);
  expect(next.sessionId).toBe(first.sessionId);
  expect(next.commit.sha).toBe(sha);
  expect(next.replyTo).toEqual({reviewId:first.id,commentId:first.comments[0].id});
  await expect(page.locator('.thread-history')).toContainText('billing account');
  await page.locator('#overall-scope').click();
  await expect(page.locator('#title')).toHaveText('Overall changes');
  await expect(page.locator('#feed')).toContainText('USD');
  await expect(page.locator('#feed')).toContainText(f.project.path);
  await expect(page.locator('#commit-approve')).toBeHidden();
  await page.locator('#timeline-open').click();
  await expect(rows.first()).toContainText('Approved');
  await rows.last().click();
  await expect(page.locator('.file-card .thread')).toContainText('Where is the account configured?');
  await run.end();
  expect(await run.exited).toBe(0);
});
